"""Статусы инструментов. Различие между отказом и отсутствием данных создаёт код, а не модель."""

from enum import StrEnum


class Status(StrEnum):
    # Данные есть и разрешены.
    OK = "ok"
    # Закрыто: документ, таблица, все названные участки, оборудование чужого участка.
    DENIED = "denied"
    # Документа или оборудования с таким идентификатором нет.
    NOT_FOUND = "not_found"
    # Запрос разрешён, строк или фрагментов нет.
    EMPTY = "empty"
    # Подготовка заявки: в сообщении пользователя нет идентификатора оборудования.
    NEEDS_IDENTIFIER = "needs_identifier"
    # Аргументы вызова не прошли схему.
    INVALID = "invalid"
